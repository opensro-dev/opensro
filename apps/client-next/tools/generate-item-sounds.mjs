import { CLIENT_PUBLIC_ROOT } from "../../../scripts/lib/generatedRoot.mjs";
import fs from "node:fs";
import { createHash } from "node:crypto";
import { pathToFileURL } from "node:url";
export function itemSoundSource( bytes ) {
	const catalog = JSON.parse( bytes ), rows = {}, drops = {};
	for ( const row of catalog.rules ) {
		if ( row.object !== "ITEM" || ![ "SND_EQUIP", "SND_DROPITEM" ].includes( row.handle ) ) continue;
		if ( row.skillId !== "-" || row.event2 !== "-" || row.event3 !== "-" ) {
			throw Error( "New ITEM selector dimensions require review" );
		}
		if ( !row.publicPath ) continue; // Reported by the whole-surface audit, never substitute a WAV.
		if ( !row.publicPath.startsWith( "/assets/audio/" ) || row.publicPath.includes( ".." ) ) {
			throw Error( "Invalid item sound path" );
		}
		((row.handle === "SND_EQUIP" ? rows : drops)[row.event1] ??= []).push( {
			path: row.publicPath,
			volume: row.volume
		} );
	}
	return `// Generated by tools/generate-item-sounds.mjs; preserves native row order.\n// effectsound.json SHA256 ${
		createHash( "sha256" ).update( bytes ).digest( "hex" )
	}\nexport function createItemSoundCatalog():Readonly<Record<string,readonly {readonly path:string;readonly volume:number}[]>>{return ${
		JSON.stringify( rows, null, 2 )
	};}\nexport function createItemDropSoundCatalog():Readonly<Record<string,readonly {readonly path:string;readonly volume:number}[]>>{return ${
		JSON.stringify( drops, null, 2 )
	};}\n`;
}
if ( process.argv[1] && import.meta.url === pathToFileURL( process.argv[1] ).href ) {
	const bytes = fs.readFileSync( CLIENT_PUBLIC_ROOT + "/assets/audio/effectsound.json" );
	const target = new URL( "../src/engine/foundation/audio/item-sound-catalog.ts", import.meta.url ),
		source = itemSoundSource( bytes );
	if ( process.argv.includes( "--write" ) ) fs.writeFileSync( target, source );
	else if ( !fs.existsSync( target ) || fs.readFileSync( target, "utf8" ) !== source ) {
		throw Error( "ITEM sound catalog drift; run node tools/generate-item-sounds.mjs --write" );
	}
	console.log( "ITEM sound catalog: PASS" );
}
