/*
===========================================================================

census-verdict.mjs - judges a built action census against the committed one

The action census (ui-action-census.mjs) is two jobs: building the table,
which drives every scene and costs minutes, and judging it against
tests/runtime/ui-action-census.json, which costs milliseconds. They are
kept apart so the gate (ui-action-census-gate.mjs) can reuse a table built
from the same inputs and judge it again whenever only the committed file
moved: a census refresh commit (#4603) used to cost r204n a full 468 s
rebuild of a table that could not have changed.

This module owns the table's form (censusTable, censusText) and its
judgement; the tool and the gate both call it.

===========================================================================
*/

import { EXPANDED_BUILD } from "../../../scripts/lib/expandedBuild.mjs";
import { lostNativeRow } from "./census-expanded.mjs";
import { replacedWindows } from "./replaced-windows.mjs";

/*
================
canonical

The value with every object's keys sorted, so equal tables print equal.
================
*/
export function canonical( value ) {
	if ( Array.isArray( value ) ) return value.map( canonical );
	if ( value && typeof value === "object" ) {
		const out = {};
		for ( const key of Object.keys( value ).sort() ) out[key] = canonical( value[key] );
		return out;
	}
	return value;
}

/*
================
censusText

The committed form of a built table: canonical JSON, tab-indented, one
trailing newline.
================
*/
export function censusText( table ) {
	return JSON.stringify( canonical( table ), null, "\t" ) + "\n";
}

const CENSUS_ABOUT = "Generated by tools/ui-action-census.mjs. Do not edit: regenerate with --write. " +
	"A null row is a recorded no-op; any routing change that alters a row fails --check (#2515).";

/*
================
censusTable

The table over every scene in names order, from built scene parts
({ name: { census } }): the tool's full build and the gate's mix of kept
and rebuilt scenes assemble it here, so both write the same text.
================
*/
export function censusTable( names, scenes ) {
	const ordered = {};
	for ( const name of names ) ordered[name] = scenes[name].census;
	return { about: CENSUS_ABOUT, scenes: ordered };
}

/*
================
censusVerdict

Whether the built census text answers the committed one: byte-equal, or,
on a build that publishes more than the native windows (an expanded build,
or one that replaces a native window with a later client's, #3971), every
committed native row surviving. Returns { ok, lines }: the lines the tool
prints, on stdout for a pass and on stderr for a failure.

expanded and replaced default to this build's own facts; the tests pass
their own.
================
*/
export function censusVerdict(
	current,
	text,
	expanded = EXPANDED_BUILD,
	replaced = replacedWindows().map( window => window.controlPrefix )
) {
	const table = JSON.parse( text );
	const sceneCount = Object.keys( table.scenes ).length;
	const rowCount = Object.values( table.scenes )
		.reduce( ( sum, scene ) => sum + Object.keys( scene.rows ).length, 0 );
	if ( current === text ) {
		return { ok: true, lines: [ `ui-action-census: up to date (${sceneCount} scenes, ${rowCount} control rows)` ] };
	}
	if ( current && (expanded || replaced.length > 0) ) {
		const lost = lostNativeRow( JSON.parse( current ), table, canonical, replaced );
		if ( lost === undefined ) {
			return {
				ok: true,
				lines: [ `ui-action-census: every native row survives the expanded build (${rowCount} control rows)` ]
			};
		}
		return { ok: false, lines: [ `ui-action-census: expanded build: ${lost}` ] };
	}
	const lines = [
		"ui-action-census: tests/runtime/ui-action-census.json is stale or differs; " +
		"run node tools/ui-action-census.mjs --write and review the row diff"
	];
	if ( current ) {
		const before = JSON.parse( current );
		for ( const name of Object.keys( table.scenes ) ) {
			if ( JSON.stringify( canonical( before.scenes?.[name] ) ) !== JSON.stringify( table.scenes[name] ) ) {
				lines.push( `first differing scene: ${name}` );
				break;
			}
		}
	}
	return { ok: false, lines };
}
