/*
===========================================================================

devstack.go - the local development stack's ports, from one setting

A developer machine runs one checkout-owned stack: the Nomad development
agent (4646-4648), the Agent (8787), its provisioning API (8789) and the
first shard's public read API (8790), and the client dev servers the Agent
admits as origins (5180 and the rest of developmentAllowedOrigins).
SRO_DEV_PORT_OFFSET moves every one of them by the same amount, so a second stack (another checkout or worktree,
with its own .state and its own shard catalogue) runs beside the first
under its own Nomad agent and its own workload identity. Unset or 0 is
today's stack exactly.

The shard ports are not moved here: they come from the shard catalogue,
which -catalog already selects.

===========================================================================
*/

package main

import (
	"fmt"
	"net"
	"net/url"
	"strconv"
	"strings"

	agentapi "opensro.online/server/internal/agent/api"
	"opensro.online/server/internal/agent/provisioning"
	"opensro.online/server/internal/agent/publicstats"
)

// EnvDevPortOffset names the setting: a whole number added to every local
// development stack port.
const EnvDevPortOffset = "SRO_DEV_PORT_OFFSET"

const (
	// devNomadHTTPPort, devNomadRPCPort and devNomadSerfPort are Nomad's
	// own defaults, which dev-windows.hcl leaves in place.
	devNomadHTTPPort = 4646
	devNomadRPCPort  = 4647
	devNomadSerfPort = 4648
	// maxDevPortOffset keeps the highest moved port (the public API's) a
	// valid TCP port with room to spare.
	maxDevPortOffset = 50000
)

/*
================
devStack

The zero value is today's single local stack.
================
*/
type devStack struct {
	offset int
}

/*
================
loadDevStack

Reads SRO_DEV_PORT_OFFSET through getenv. A value that is not a whole
number in 0..maxDevPortOffset stops the command naming the setting.
================
*/
func loadDevStack(getenv func(string) string) (devStack, error) {
	text := strings.TrimSpace(getenv(EnvDevPortOffset))
	if text == "" {
		return devStack{}, nil
	}
	offset, err := strconv.Atoi(text)
	if err != nil || offset < 0 || offset > maxDevPortOffset {
		return devStack{}, fmt.Errorf(
			"%s=%q: want a whole number from 0 to %d",
			EnvDevPortOffset,
			text,
			maxDevPortOffset,
		)
	}
	return devStack{offset: offset}, nil
}

/*
================
devStack.moved
================
*/
func (s devStack) moved() bool {
	return s.offset != 0
}

/*
================
devStack.allowedOrigins

developmentAllowedOrigins with every port moved: the moved stack's client
dev servers (5180 becomes 5280 at +100) are the origins its Agent admits.
================
*/
func (s devStack) allowedOrigins() string {
	origins := strings.Split(developmentAllowedOrigins, ",")
	for i, origin := range origins {
		u, err := url.Parse(origin)
		if err != nil {
			panic(err)
		}
		u.Host = net.JoinHostPort(u.Hostname(), strconv.Itoa(loopbackPort(u.Host)+s.offset))
		origins[i] = u.String()
	}
	return strings.Join(origins, ",")
}

/*
================
devStack.nomadAddress

The development agent's HTTP API, which is also its workload identity
issuer (dev-windows.hcl, and devStack.portsConfig when moved).
================
*/
func (s devStack) nomadAddress() string {
	return "http://127.0.0.1:" + strconv.Itoa(devNomadHTTPPort+s.offset)
}

/*
================
devStack.agentPort
================
*/
func (s devStack) agentPort() int {
	return loopbackPort(agentapi.DefaultAddr) + s.offset
}

/*
================
devStack.provisioningPort
================
*/
func (s devStack) provisioningPort() int {
	return provisioning.DefaultPort + s.offset
}

/*
================
devStack.publicAPIAddr

The first shard's public read API listener.
================
*/
func (s devStack) publicAPIAddr() string {
	host, _, _ := net.SplitHostPort(publicstats.DefaultAddr)
	return net.JoinHostPort(host, strconv.Itoa(loopbackPort(publicstats.DefaultAddr)+s.offset))
}

/*
================
devStack.portsConfig

The Nomad agent config merged after dev-windows.hcl when the stack is moved:
its three ports and the issuer that names the moved HTTP port. Empty for
the default stack, whose agent command line stays exactly as before.
================
*/
func (s devStack) portsConfig() string {
	if s.offset == 0 {
		return ""
	}
	return fmt.Sprintf(
		"# Generated by sro-nomad dev-agent: %s=%d.\n"+
			"ports {\n  http = %d\n  rpc  = %d\n  serf = %d\n}\n\n"+
			"server {\n  oidc_issuer = %q\n}\n",
		EnvDevPortOffset,
		s.offset,
		devNomadHTTPPort+s.offset,
		devNomadRPCPort+s.offset,
		devNomadSerfPort+s.offset,
		s.nomadAddress(),
	)
}

/*
================
loopbackPort

The port of one of the compiled-in loopback defaults; they are constants,
so a malformed one is a programming error.
================
*/
func loopbackPort(addr string) int {
	_, text, err := net.SplitHostPort(addr)
	if err != nil {
		panic(err)
	}
	port, err := strconv.Atoi(text)
	if err != nil {
		panic(err)
	}
	return port
}
