/*
===========================================================================
petwolfhunt.go - port-only shared prey mark consumed by a committed Savage Rend.

Normal attacks charge once; credited bonus hits never re-enter attack counters.
The division owns this transient state, with no persisted rank/schema change.
===========================================================================
*/
package action

import (
	"opensro.online/server/internal/game/combat"
	"opensro.online/server/internal/game/companion"
	"opensro.online/server/internal/game/enterworld"
	"opensro.online/server/internal/game/item/wire"
	"opensro.online/server/internal/game/world/monster"
	"opensro.online/server/internal/game/world/simulation"
)

const wolfHuntCharges = 4
const wolfHuntDurationMs = 8000
const wolfHuntRadius = 6 * petAreaPerMeter
const wolfHuntBurstTargets = 5

/*
================
wolfHuntAttack

The first damaged victim owns this action's charge. Retargeting replaces the
old mark; secondary hits, periodic effects and procs cannot multiply charges.
================
*/
func (rt *Runtime) wolfHuntAttack(step petCombatStep, actor int, targets []uint32) {
	s, _, ok := companion.Passive(step.pet, "Blood Hunt", companion.ModifiersFor(step.pet))
	if !ok || actor == 1 && s.Option < 2 || len(targets) == 0 {
		return
	}
	run := &step.state.wolf
	gid := targets[0]
	mob, ok := rt.Monsters.Get(step.key.division, gid)
	if !ok || mob.CurrentHP == 0 {
		return
	}
	if run.huntBook != s.ID || run.huntTarget != gid || run.huntUntil <= step.nowMs {
		run.huntBook, run.huntTarget, run.huntHits = s.ID, gid, 0
	}
	run.huntHits = min(wolfHuntCharges, run.huntHits+1)
	run.huntUntil = step.nowMs + wolfHuntDurationMs
}

/*
================
wolfHuntRend

Only a landed Rend on previously marked prey consumes it. The bonus scales
from committed direct damage; a dead primary can still release the tier-III
burst. No animation, bleeding refresh or extra attack is generated by a proc.
================
*/
func (rt *Runtime) wolfHuntRend(step petCombatStep, primary petCombatTarget, strike monsterStrike) {
	if step.trained == nil || !step.trained.rend || primary.monster == nil || !petStrikeDamaged(strike) {
		return
	}
	live, ok := rt.wolfCompanion(step.key.division, step.state.character, step.pet.GID, step.nowMs)
	if !ok {
		return
	}
	s, level, ok := companion.Passive(live.pet, "Blood Hunt", companion.ModifiersFor(live.pet))
	run := &step.state.wolf
	if !ok || run.huntBook != s.ID || run.huntHits != wolfHuntCharges || run.huntTarget != primary.gid || run.huntUntil <= step.nowMs {
		return
	}
	run.huntHits, run.huntTarget = 0, 0
	var damage uint64
	for _, hit := range strike.impacts {
		if !hit.Blocked {
			damage += uint64(hit.Damage)
		}
	}
	bonus := uint32(min(float64(wire.MaxSkillActionDamage), float64(damage)*s.ValueAt(level)/100))
	mob, found := rt.Monsters.Get(step.key.division, primary.gid)
	if found && mob.CurrentHP > 0 {
		rt.wolfBonusHit(step, mob, bonus, "wolf-blood-hunt")
	}
	if s.Option != 3 || bonus < 2 {
		return
	}
	lease, found := rt.casterPopulation(step.key.division, step.snapshot)
	if !found {
		return
	}
	world, _ := step.state.follower.Presentation()
	count := 0
	for _, candidate := range rt.Monsters.CombatCandidatesInPopulation(step.key.division, lease, primary.at, wolfHuntRadius, step.nowMs, false) {
		target, valid := rt.resolvePetCombatTarget(step, candidate.Gid)
		if !valid || target.monster == nil || target.gid == primary.gid || !petTargetBleeds(*target.monster) || !samePlaneAdjacent(primary.at, target.at) || areaDistance(primary.at, target.at) > wolfHuntRadius {
			continue
		}
		if rt.LineOfSight != nil && !rt.LineOfSight(step.state.follower.Position(step.nowMs), world.LiveOwnerAt(step.nowMs), target.at) {
			continue
		}
		rt.wolfBonusHit(step, *target.monster, bonus/2, "wolf-blood-hunt-burst")
		count++
		if count >= wolfHuntBurstTargets {
			break
		}
	}
}

/*
================
wolfBonusHit

Use the normal expected-HP, rewards and audience doors. No raw HP mutation,
recursive cast, attack charge or duplicate reward settlement.
================
*/
func (rt *Runtime) wolfBonusHit(step petCombatStep, mob monster.Instance, damage uint32, reason string) {
	if damage == 0 || mob.CurrentHP == 0 {
		return
	}
	// The population selectors that feed this sink skip the owner's attack
	// validation; a bandit of the owner's own side takes no bonus (#2080).
	if rt.jobMonsterTargetRefusal(step.snapshot, mob) != 0 {
		return
	}
	hit, committed := rt.commitCompanionCreditedMonsterHit(step.key.division, step.state.character, step.snapshot, enterworld.SkillRow{}, mob, combat.Result{Damage: damage}, reason, step.nowMs)
	if !committed {
		return
	}
	if action := wolfBonusEmote(reason); action != 0 {
		rt.wolfEmote(step.key.division, mob.Gid, action)
	}
	public := []wire.Frame{{Opcode: simulation.OpVitalsUpdate, Payload: simulation.HPRefreshPayload(mob.Gid, 0, hit.impacts[0].CurrentHP)}}
	result := rt.creditedHitResult(step.key.division, mob, hit, public, step.nowMs)
	if reason == "pet-gear-element" {
		result.ActorPrivate = append(result.ActorPrivate, abnormalDamageFrame(mob.Gid, hit.impacts[0].Damage))
	}
	batches := []simulation.DivisionFrames{{DivisionID: step.key.division, SourceGID: mob.Gid, Frames: simFrames(result.Broadcast)}}
	if len(result.ActorPrivate) > 0 {
		batches = append(batches, simulation.DivisionFrames{DivisionID: step.key.division, OnlyCharacterID: step.state.character.ID, Frames: simFrames(result.ActorPrivate)})
	}
	batches = append(batches, recipientDivisionFrames(step.key.division, result.Recipients)...)
	rt.queueMonsterLegFrames(rt.sealTickPrivate(batches))
}
