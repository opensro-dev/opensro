# ===========================================================================
#
# pet_design_export.py - validate the pet design and generate its client copy
#
# Port-only, not native. The server's embedded petdesign.json is the one
# source of the attack-pet design (#1631): the server compiles it in and the
# asset build (scripts/build/shared/portItemRows.mjs) reads it in place. The
# client keeps a generated module so the design's literal types reach its
# code. Edit the JSON, then run this tool; --check (check:pet-design) fails
# when the JSON's canonical layout or the client module is out of date.
#
# ===========================================================================
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = "apps/server/internal/game/companion/petdesign.json"
CLIENT_MODULE = "apps/client-next/src/engine/foundation/ui/pet-design-data.ts"
SECTIONS = ("rules", "pets", "skills", "treeSkills", "gear", "affixes", "procs")
UNIQUE_ID_SECTIONS = ("skills", "treeSkills", "affixes")
GEAR_DEGREES = 9
TREE_SKILL_BOOKS = 60


# ================
# validate
#
# The shape every consumer relies on; a malformed design never reaches them.
# ================
def validate(design):
	for key in SECTIONS:
		if key not in design:
			raise ValueError("Missing section: " + key)
	for key in UNIQUE_ID_SECTIONS:
		ids = [row["id"] for row in design[key]]
		if len(ids) != len(set(ids)):
			raise ValueError("Duplicate IDs in " + key)
	if len(design["gear"]) != GEAR_DEGREES or len(design["treeSkills"]) != TREE_SKILL_BOOKS:
		raise ValueError("Expected nine degrees and sixty skill books")


# ================
# render
#
# The source's canonical text and the client module generated from it.
# ================
def render(design):
	text = json.dumps(design, ensure_ascii=False, indent="\t") + "\n"
	module = "// Generated by scripts/tools/pet_design_export.py from " + SOURCE + " - do not edit.\n"
	module += "export const PET_DESIGN = " + text.rstrip() + " as const;\n"
	return {SOURCE: text, CLIENT_MODULE: module}


# ================
# main
# ================
def main(argv):
	check = "--check" in argv
	design = json.loads((ROOT / SOURCE).read_text(encoding="utf-8"))
	validate(design)
	stale = []
	for path, text in render(design).items():
		target = ROOT / path
		if target.exists() and target.read_bytes() == text.encode("utf-8"):
			continue
		if check:
			stale.append(path)
		else:
			target.write_text(text, encoding="utf-8", newline="\n")
	if stale:
		print("pet design out of date; run python scripts/tools/pet_design_export.py: " + ", ".join(stale))
		return 1
	return 0


if __name__ == "__main__":
	sys.exit(main(sys.argv[1:]))
