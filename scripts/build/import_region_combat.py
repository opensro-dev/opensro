"""
===========================================================================
import_region_combat.py - recover region combat permissions from reference data

Reads the named primary _RefRegion allocation in a research SQL backup.
Produces immutable ranges; it never restores or modifies a database.
===========================================================================
"""

import argparse
import hashlib
import pathlib
import struct

from loot_sql_pages import Backup


# ================
# read_regions
# ================
def read_regions(path):
	backup = Backup(path)
	regions = {}
	try:
		for _, at, page in backup.named_rows("_RefRegion"):
			fixed = struct.unpack_from("<H", page, at + 2)[0]
			columns = struct.unpack_from("<H", page, at + fixed)[0]
			if fixed != 65 or columns != 21:
				raise ValueError("Unsupported _RefRegion row layout")
			# wRegionID is the lookup key. X/Z are separate authored columns;
			# dungeon records intentionally leave both at zero.
			region = struct.unpack_from("<H", page, at + 4)[0]
			battlefield = page[at + 8]
			if battlefield not in (0, 1):
				raise ValueError("Invalid battlefield permission")
			if region in regions and regions[region] != battlefield:
				raise ValueError("Conflicting region combat permissions")
			regions[region] = battlefield
	finally:
		backup.close()
	if not regions:
		raise ValueError("Empty region combat catalog")
	return regions


# ================
# region_ranges
# ================
def region_ranges(regions):
	ranges = []
	for region, allowed in sorted(regions.items()):
		if ranges and ranges[-1][1] + 1 == region and ranges[-1][2] == allowed:
			ranges[-1][1] = region
		else:
			ranges.append([region, region, allowed])
	return ranges


# ================
# go_lines
#
# The server table (apps/server/internal/game/world/regioncombat_generated.go).
# ================
def go_lines(digest, rows, ranges):
	lines = [
		"// Generated by scripts/build/import_region_combat.py; DO NOT EDIT.",
		"// _RefRegion source SHA256: " + digest,
		"// Catalog rows: " + str(rows),
		"package world",
		"",
		"var regionCombatRanges = [...]regionCombatRange{",
	]
	for first, last, allowed in ranges:
		lines.append(f"\t{{0x{first:04x}, 0x{last:04x}, {str(bool(allowed)).lower()}}},")
	lines.extend(["}", ""])
	return lines


# ================
# client_lines
#
# The client's copy of the same ranges
# (apps/client-next/src/engine/foundation/gameplay/region-combat-ranges.ts),
# written from the same parse so the two tables cannot drift
# (scripts/test/python/test_region_combat_parity.py pins them together).
# ================
def client_lines(digest, rows, ranges):
	lines = [
		"// Generated by scripts/build/import_region_combat.py; DO NOT EDIT.",
		"// _RefRegion source SHA256: " + digest,
		"// Catalog rows: " + str(rows),
		"",
		"export type RegionCombatRange = {",
		"\treadonly first: number;",
		"\treadonly last: number;",
		"\treadonly allowed: boolean;",
		"};",
		"",
		"export const REGION_COMBAT_RANGES: readonly RegionCombatRange[] = [",
	]
	for first, last, allowed in ranges:
		lines.append(f"\t{{ first: 0x{first:04x}, last: 0x{last:04x}, allowed: {str(bool(allowed)).lower()} }},")
	lines.extend(["];", ""])
	return lines


# ================
# main
# ================
def main():
	parser = argparse.ArgumentParser(description=__doc__)
	parser.add_argument("backup", type=pathlib.Path)
	parser.add_argument("output", type=pathlib.Path, help="the server table (regioncombat_generated.go)")
	parser.add_argument("--client-output", type=pathlib.Path, help="the client table (region-combat-ranges.ts)")
	args = parser.parse_args()
	regions = read_regions(args.backup)
	with args.backup.open("rb") as source:
		digest = hashlib.file_digest(source, "sha256").hexdigest()
	ranges = region_ranges(regions)
	args.output.write_text("\n".join(go_lines(digest, len(regions), ranges)), encoding="utf-8", newline="\n")
	if args.client_output:
		args.client_output.write_text("\n".join(client_lines(digest, len(regions), ranges)), encoding="utf-8", newline="\n")
	print(f"Generated {len(regions)} region permissions")


if __name__ == "__main__":
	main()
