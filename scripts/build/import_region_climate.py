"""
===========================================================================
import_region_climate.py - recover the region climates from reference data

Reads the named primary _RefClimate and _RefRegion allocations in a research
SQL backup: every climate's weather parameters, and the climate each region
names. Produces an immutable Go table and inclusive, non-overlapping region
ranges for the server's weather cycle (internal/game/world/climate). It never
restores or modifies a database.
===========================================================================
"""

import argparse
import hashlib
import pathlib
import struct

from loot_sql_pages import Backup


# The _RefClimate fixed part: the 4-byte row header, then ID, the initial
# weather and amount, the change switch, the division, the spell duration
# and its variance, and the snow and rain amounts, variances and chances.
CLIMATE_FIXED = 0x1a
CLIMATE_LAYOUT = "<iBBBBiiBBBBBB"
CLIMATE_FIELDS = (
	"id", "initial_weather", "initial_amount", "change_weather", "division",
	"duration", "duration_variance", "snowfall", "snowfall_variance", "prob_snow",
	"rainfall", "rainfall_variance", "prob_rain",
)

# The _RefRegion fixed part (import_region_combat.py reads the same row).
REGION_FIXED = 65
REGION_COLUMNS = 21


# ================
# read_climates
# ================
def read_climates(backup):
	climates = {}
	for _, at, page in backup.named_rows("_RefClimate"):
		fixed = struct.unpack_from("<H", page, at + 2)[0]
		if fixed != CLIMATE_FIXED:
			raise ValueError("Unsupported _RefClimate row layout")
		row = dict(zip(CLIMATE_FIELDS, struct.unpack_from(CLIMATE_LAYOUT, page, at + 4)))
		if row["id"] in climates and climates[row["id"]] != row:
			raise ValueError("Conflicting climate rows")
		climates[row["id"]] = row
	if not climates:
		raise ValueError("Empty climate catalog")
	return climates


# ================
# read_regions
# ================
def read_regions(backup):
	regions = {}
	for _, at, page in backup.named_rows("_RefRegion"):
		fixed = struct.unpack_from("<H", page, at + 2)[0]
		columns = struct.unpack_from("<H", page, at + fixed)[0]
		if fixed != REGION_FIXED or columns != REGION_COLUMNS:
			raise ValueError("Unsupported _RefRegion row layout")
		# wRegionID is the lookup key; Climate follows the battlefield byte.
		region = struct.unpack_from("<H", page, at + 4)[0]
		climate = struct.unpack_from("<i", page, at + 9)[0]
		if region in regions and regions[region] != climate:
			raise ValueError("Conflicting region climates")
		regions[region] = climate
	if not regions:
		raise ValueError("Empty region climate catalog")
	return regions


# ================
# region_ranges
# ================
def region_ranges(regions):
	ranges = []
	for region, climate in sorted(regions.items()):
		if ranges and ranges[-1][1] + 1 == region and ranges[-1][2] == climate:
			ranges[-1][1] = region
		else:
			ranges.append([region, region, climate])
	return ranges


# ================
# main
# ================
def main():
	parser = argparse.ArgumentParser(description=__doc__)
	parser.add_argument("backup", type=pathlib.Path)
	parser.add_argument("output", type=pathlib.Path)
	args = parser.parse_args()
	backup = Backup(args.backup)
	try:
		climates = read_climates(backup)
		regions = read_regions(backup)
	finally:
		backup.close()
	missing = sorted({climate for climate in regions.values() if climate not in climates})
	if missing:
		raise ValueError("Regions name unknown climates: " + ", ".join(map(str, missing)))
	with args.backup.open("rb") as source:
		digest = hashlib.file_digest(source, "sha256").hexdigest()
	lines = [
		"// Generated by scripts/build/import_region_climate.py; DO NOT EDIT.",
		"// _RefClimate and _RefRegion source SHA256: " + digest,
		"// Climate rows: " + str(len(climates)) + ", region rows: " + str(len(regions)),
		"package climate",
		"",
		"var climateRows = [...]Row{",
	]
	for _, row in sorted(climates.items()):
		lines.append(
			"\t{{ID: {id}, InitialWeather: {initial_weather}, InitialAmount: {initial_amount}, "
			"ChangeWeather: {change_weather}, Division: {division}, Duration: {duration}, "
			"DurationVariance: {duration_variance}, Snowfall: {snowfall}, SnowfallVariance: {snowfall_variance}, "
			"ProbSnow: {prob_snow}, Rainfall: {rainfall}, RainfallVariance: {rainfall_variance}, "
			"ProbRain: {prob_rain}}},".format(**row)
		)
	lines.extend(["}", "", "var regionClimateRanges = [...]regionClimateRange{"])
	for first, last, climate in region_ranges(regions):
		lines.append(f"\t{{0x{first:04x}, 0x{last:04x}, {climate}}},")
	lines.extend(["}", ""])
	args.output.write_text("\n".join(lines), encoding="utf-8", newline="\n")
	print(f"Generated {len(climates)} climates and {len(regions)} region climates")


if __name__ == "__main__":
	main()
