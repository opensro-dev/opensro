"""
===========================================================================
build_penguin_blizzard_atlas.py - compile the owned PNG into an embedded BC3 atlas.

The original art stays editable. The client uploads the compiled blocks or
uses its existing software BC3 decoder on GPUs without block compression.
===========================================================================
"""
import base64
import hashlib
import io
import json
from pathlib import Path

from PIL import Image


def main():
	"""Compile four isolated cells with transparent filtering gutters."""
	name = "penguin-blizzard"
	root = Path(__file__).resolve().parents[3]
	symbol = "penguinBlizzardAtlas"
	filename = "frost-wind.png"
	source = root / "apps/client-next/art/pets" / name / filename
	image = Image.open(source).convert("RGBA")
	atlas = Image.new("RGBA", (512, 512))
	for cell in range(4):
		x, y = cell % 2, cell // 2
		tile = image.crop((x * image.width // 2, y * image.height // 2,
			(x + 1) * image.width // 2, (y + 1) * image.height // 2))
		tile.thumbnail((224, 224), Image.Resampling.LANCZOS)
		# Very faint alpha-matte RGB must not pollute a BC3 block's palette.
		tile.putdata([(0, 0, 0, 0) if a < 8 else (r, g, b, a)
			for r, g, b, a in tile.getdata()])
		atlas.paste(tile, (x * 256 + 16, y * 256 + 16))
	encoded = io.BytesIO()
	atlas.save(encoded, format="DDS", pixel_format="DXT5")
	dds = encoded.getvalue()
	assert dds[:4] == b"DDS " and dds[84:88] == b"DXT5"
	assert len(dds) == 128 + 512 * 512
	output = root / "apps/client-next/src/engine/foundation/assets" / (name + "-atlas.ts")
	metadata = {
		"sourceSha256": hashlib.sha256(source.read_bytes()).hexdigest(),
		"width": 512, "height": 512,
		"blocks": base64.b64encode(dds[128:]).decode("ascii")
	}
	output.write_text(
		"/*\n===========================================================================\n"
		f"{name}-atlas.ts - owned pet particle texture blocks.\n"
		"Generated by scripts/build/char/build_penguin_blizzard_atlas.py; do not edit.\n"
		"===========================================================================\n*/\n"
		+ "export const " + symbol + " = " + json.dumps(metadata, indent=2)
		+ " as const;\n", encoding="utf-8", newline="\n")

	print("Compiled owned pet atlas: 512x512 BC3, 262144 bytes")


if __name__ == "__main__":
	main()
